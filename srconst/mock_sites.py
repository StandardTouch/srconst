def _make_block(prefix, name, floors, units_per_floor, pos_x, pos_z, color, cat_key, seed):
    templates = unit_catalog.get(cat_key, unit_catalog["imperial_8"])
    flats = []
    for fl in range(1, floors + 1):
        rise = (fl - 1) * 50000
        for u in range(units_per_floor):
            tmpl = templates[u % len(templates)]
            uidx = u + 1
            h = (fl * 7 + uidx * 11 + seed) % 10
            status = "Available" if h < 5 else ("In Process" if h < 8 else "Sold")
            flats.append({
                "name": f"{prefix}-{fl}{uidx:02d}",
                "unitIndex": uidx,
                "floor": f"Floor {fl:02d}",
                "floorNumber": fl,
                "type": tmpl["type"],
                "facing": tmpl["facing"],
                "area": tmpl["area"],
                "carpetArea": tmpl["carpetArea"],
                "price": tmpl["basePrice"] + rise,
                "status": status,
                "inside3dRender": tmpl["render"],
                "dims": tmpl["dims"],
                "features": ["Vastu Compliant", "Private Balcony", "Premium Finishes"]
            })
    return {
        "name": name,
        "prefix": prefix,
        "totalFloors": floors,
        "unitsPerFloor": units_per_floor,
        "posX": pos_x,
        "posZ": pos_z,
        "color": color,
        "flats": flats
    }

